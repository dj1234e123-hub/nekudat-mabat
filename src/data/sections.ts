// עולמות התוכן של האתר – הקטגוריה הראשית של כל סיפור, אחת בדיוק לכל סיפור.
// החלוקה נגזרה מהתוכן עצמו (משדה המקור שבכרטיס הסיפור) ולא מתיאוריה:
// מי זה קרה לו? לאף אחד → משל · לדמות מוכרת (חכם/צדיק) → צדיקים ·
// לי או למי שפגשתי → יומן · למישהו אחר, בעולם, ותועד בפומבי → מהחיים.
//
// עולם רביעי (מהחיים) נוסף ב-2026-09-13 אחרי מחקר תוכן מלא: "מהיומן שלי"
// תפח מ-7 ל-15 סיפורים, ורובם לא היו אישיים לבעל הפרויקט אלא סיפורים
// מתועדים על זרים גמורים (עיתונות, ארכיון היסטורי, עדות) – קבוצה שגדלה
// מהר יותר מכל עולם אחר באתר ולא היה לה תא משלה בכלל. הכלל המבחין: מקור
// מזוהה וציבורי (CNN, יד ושם, StoryCorps...) מול "סיפור ששמעתי" בלי מקור,
// שנשאר ביומן. פירוט מלא בתיעוד השיחה ובטבלת ההחלטות ב-CLAUDE.md.
//
// slug באנגלית לכתובות נקיות; התווית והשורה בעברית לתצוגה.
// accent – צבע מותג אחד לכל עולם, מופיע כקו דק בדלת ובתווית שבכרטיס.
// linkText – נוסח הקישור אל העולם ("כל המשלים"). חי כאן ולא בעמוד מסוים,
// כי גם דף הבית וגם עמוד הסיפורים צריכים אותו.
// hidden – עולם ששמור לעתיד ואין בו עדיין תוכן: אינו מוצג כדלת בעמוד הסיפורים
// (דלת ריקה נראית כתקלה), אבל קיים בסכמה ונפתח מעצמו ברגע שיהיו בו סיפורים.
//
// **השורה מסבירה ולא רומזת.** הנוסח הקודם היה פיוטי ("סיפור שלא קרה – כדי
// שתראה בו את מה שכן") ויפה כשלעצמו, אבל הוא תיאר את *הרעיון* של העולם ולא
// את מה שהקורא ימצא בו. השורה היא גם תיאור המטא של עמוד העולם בגוגל, ולכן
// משפט שמסביר עובד שם טוב יותר ממשפט שרומז.
