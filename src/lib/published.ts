// כלל פרסום אחד לכל האתר: תוכן עם תאריך עתידי (ביחס לרגע הבנייה) אינו נבנה —
// לא ברשימה, לא בעמוד שלו, ולא במפת האתר (שנגזרת מהעמודים שבאמת נבנו).
//
// חל על כל שישה האוספים (stories, moments, momentsEs, storiesEs, mabatEs,
// mabatLeshabbat) — לכולם שדה date, ולכולם אותו כלל בדיוק.
//
// האתר סטטי ואינו בודק שום דבר בזמן אמת, ולכן זו רשת ביטחון ולא שעון: מי
// שדוחף תוכן מתוזמן מוקדם מדי, פשוט לא עולה עד לבנייה הבאה שקורית אחרי
// התאריך שנקבע לו. את הבנייה הזו בזמן הנכון עדיין צריך מישהו להפעיל.
export function isPublished<T extends { data: { date: Date } }>(entry: T): boolean {
  return entry.data.date.getTime() <= Date.now();
}
