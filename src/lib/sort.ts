// כלל המיון של האתר: מהחדש לישן, עם שובר שוויון קבוע.
//
// **למה שובר השוויון הכרחי.** רוב הרגעים באותו מדף נכתבו באותו יום, ולכן
// מיון לפי תאריך בלבד משאיר אותם שווים — ואז הסדר נקבע לפי מה שמנוע הבנייה
// במקרה מחזיר. זה נתגלה בשדרוג ל-Astro 7: אותם שלושה רגעים, סדר אחר, בלי
// שאיש נגע בתוכן. סדר שנקבע במקרה משתנה בכל שדרוג בשקט.
//
// שם הקובץ יורד (`b` לפני `a`) הוא אותה מוסכמה שכבר הייתה בדף הבית ובדף
// הבית הספרדי: בתאריך זהה, המזהה המאוחר נחשב החדש יותר.
interface Sortable {
  id: string;
  data: { date: Date };
}

export function newestFirst(a: Sortable, b: Sortable): number {
  const byDate = b.data.date.getTime() - a.data.date.getTime();
  return byDate !== 0 ? byDate : b.id.localeCompare(a.id);
}
